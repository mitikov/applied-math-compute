"""Лабораторна 1. Підготовче завдання: відтворюваний чистий запуск.

Усі вхідні дані зібрані в одному місці. Скрипт не залежить
від попереднього стану Jupyter kernel і дає той самий результат
після кожного нового запуску з тими самими даними.
"""


# --- Вхідні дані ---
distance_km = 120.0
speed_kmh = 60.0


# --- Перевірка ---
if distance_km < 0:
    raise ValueError("Відстань не може бути від'ємною.")
if speed_kmh <= 0:
    raise ValueError("Швидкість має бути додатною.")


# --- Розрахунок ---
time_h = distance_km / speed_kmh


# --- Пояснений результат ---
print(f"Відстань: {distance_km:.1f} км")
print(f"Стала швидкість: {speed_kmh:.1f} км/год")
print(f"Оцінений час руху: {time_h:.2f} год")

