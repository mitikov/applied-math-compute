"""Лабораторна 1. Python Challenge: одна точка, одна гілка.

Демонстраційний варіант 1:
    y = a*x + b*cos(x),              якщо x < 0.5
    y = b*x^2 + c*sin(2*x),          якщо 0.5 <= x <= 1
Загальна область завдання: 0 <= x <= 1.
"""

import math


# --- Коефіцієнти варіанта 1 ---
a = 0.75
b = 1.19
c = -2.5

# Змініть x для перевірки іншої точки.
x = 0.5


# --- Перевірка області та вибір гілки ---
if not 0 <= x <= 1:
    print(f"x = {x} поза областю [0, 1].")
else:
    if x < 0.5:
        branch = 1
        y = a * x + b * math.cos(x)
    else:
        branch = 2
        y = b * x ** 2 + c * math.sin(2 * x)

    print(f"x = {x}")
    print(f"гілка = {branch}")
    print(f"y = {y:.8f}")
