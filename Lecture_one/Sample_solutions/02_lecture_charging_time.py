"""Лекція 1. Завдання: оцінювач часу заряджання.

Модель: t = E / P, де E — потрібна енергія у Вт·год,
P — стала корисна потужність у Вт.
"""


# --- Вхідні дані ---
energy_wh = 60.0
power_w = 20.0


# --- Перевірка даних ---
if energy_wh < 0:
    raise ValueError("Енергія має бути невід'ємною.")
if power_w <= 0:
    raise ValueError("Потужність має бути додатною.")


# --- Обчислення ---
time_h = energy_wh / power_w
time_min = time_h * 60


# --- Незалежна перевірка ---
energy_check_wh = power_w * time_h


# --- Результат ---
print(f"Орієнтовний час: {time_h:.2f} год")
print(f"Те саме у хвилинах: {time_min:.0f} хв")
print(f"Зворотна перевірка P * t: {energy_check_wh:.2f} Вт·год")
print("Модель передбачає сталу корисну потужність протягом усього процесу.")
